CLUSTER_BY_KEY = {c.key: c for c in CLUSTERS}

# Noise: culture/EEO/reporting-line filler. Company-name phrasing is injected
# at match time, not baked into the pattern.
_NOISE_TEMPLATE = (
    r"^(in the role of|we are (considering|seeking|looking)|join (our|us)|"
    r".*(you will report to|report to the)|equal opportunity|eoe\b|"
    r".*\bour benefits\b|total rewards|applicants for)"
)


def noise_pattern(company_name: str | None = None) -> re.Pattern[str]:
    extra = rf"|{re.escape(company_name)} is (an|the)|founded by fans" if company_name else ""
    return re.compile(_NOISE_TEMPLATE + extra, re.I)


def classify(bullet: str, _clusters: list[Cluster] | None = None) -> str:
    """First-match classification with crude singularization for plurals."""
    sing = re.sub(r"(?<=[a-z])s\b", "", bullet.lower())
    for cluster in _clusters or CLUSTERS:
        if re.search(cluster.pat, bullet, re.I) or re.search(cluster.pat, sing, re.I):
            return cluster.key
    return "other_generalist"
