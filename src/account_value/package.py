"""Account package writer: README, REPORT, account-value.json, provenance."""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

from account_value import MODEL_VERSION, TAXONOMY_VERSION


def write_package(
    package_dir: Path,
    request_dict: dict,
    identity_dict: dict,
    collection_dict: dict,
    events_dict: dict,
    model: dict,
    reconciliation_dict: dict,
    validation_passed: bool,
    snapshot_date: str,
) -> None:
    package_dir.mkdir(parents=True, exist_ok=True)
    company = request_dict["company_name"]
    roles = model["roles"]

    total_base = sum(float(r["saved_hours_base"]) for r in roles)
    total_hours = sum(float(r["role_hours_annual"]) for r in roles)

    validation_label = (
        "passed" if validation_passed
        else "FAILED (published for review only — see validation-report.txt)"
    )
    readme = f"""# {company} × Factory Value

Account-value package generated by `account-value` ({MODEL_VERSION}).

- **Snapshot:** {snapshot_date}
- **Postings captured:** {len(roles)} · **Value model:** taxonomy {TAXONOMY_VERSION}
- **Identity:** {identity_dict.get('canonical_domain', 'unresolved')}
- **Validation:** {validation_label}

## Navigation

| Path | Contents |
|---|---|
| `REPORT.md` | Executive findings and rankings |
| `outputs/{company} × Factory Value.xlsx` | The standard 10-sheet workbook |
| `data/raw/` | Immutable source snapshots |
| `data/processed/` | Jobs, responsibilities, scoring, rankings |
| `account-value.json` | Machine-readable provenance and fingerprints |
| `reconciliation.json` | Overlap decisions and combined totals |
"""
    (package_dir / "README.md").write_text(readme, encoding="utf-8")

    top = sorted(roles, key=lambda r: -float(r["saved_hours_base"]))[:10]
    report_lines = [
        f"# {company} × Factory Value Report",
        f"**Snapshot:** {snapshot_date} · {len(roles)} postings · "
        f"taxonomy {TAXONOMY_VERSION}",
        "",
        "## Inherited compelling-event value",
    ]
    for component in request_dict.get("inherited_components", []):
        report_lines.append(
            f"- {component['description']} "
            f"(signal {component.get('signal_id') or 'n/a'}, "
            f"confidence {component.get('confidence', 'unknown')})"
        )
    if not request_dict.get("inherited_components"):
        report_lines.append("- (none supplied)")
    report_lines += [
        "",
        "## Job-board capacity value (base scenario)",
        f"- {total_base:,.0f} hours/year freed across {len(roles)} posting-equivalents "
        f"({100 * total_base / total_hours:.1f}% of posting capacity)"
        if total_hours else "- (no postings)",
        "",
        "## Top roles by saved hours (base)",
        "",
        "| Role | US-equiv pay | Saved h | % freed |",
        "|---|---|---|---|",
    ]
    for row in top:
        report_lines.append(
            f"| {row['title']} | ${row['us_equiv_base_pay']:,} | "
            f"{row['saved_hours_base']:.0f} | {row['pct_capacity_freed_base']}% |"
        )
    if reconciliation_dict.get("combined_blocked_reason"):
        report_lines += ["", "## Combined total", f"NOT CLAIMED — {reconciliation_dict['combined_blocked_reason']}"]
    else:
        report_lines += [
            "", "## Combined total (overlap-checked)",
            f"- saved hours/yr: {reconciliation_dict.get('combined_saved_hours_annual') or 'not established'}",
            f"- hard-cost value: {reconciliation_dict.get('combined_hard_cost_usd') or 'unknown, where looked'}",
        ]
    if events_dict.get("open_unknowns"):
        report_lines += ["", "## Open unknowns"]
        report_lines += [f"- {u}" for u in events_dict["open_unknowns"]]
    (package_dir / "REPORT.md").write_text("\n".join(report_lines) + "\n", encoding="utf-8")

    account_value = {
        "schema_version": "1",
        "model_version": MODEL_VERSION,
        "taxonomy_version": TAXONOMY_VERSION,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "request": request_dict,
        "identity": identity_dict,
        "collection": collection_dict,
        "events": events_dict,
        "reconciliation": reconciliation_dict,
        "validation_passed": validation_passed,
        "totals": {
            "saved_hours_base": round(total_base, 1),
            "portfolio_hours": round(total_hours, 1),
        },
    }
    (package_dir / "account-value.json").write_text(
        json.dumps(account_value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
